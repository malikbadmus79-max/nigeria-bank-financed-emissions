"""Write docs/phase0_results.md from the Phase 0 caches in data/interim/.

    python -m bank_emissions.phase0_check --stage report
"""

from __future__ import annotations

import json
from pathlib import Path

import pandas as pd

from .sources import BANKS, ENTITY_TYPE, IR_NOTES, YEARS

ROOT = Path(__file__).resolve().parents[2]
INTERIM = ROOT / "data" / "interim"
DOCS = ROOT / "docs"


def _load(name):
    p = INTERIM / name
    return json.loads(p.read_text(encoding="utf-8")) if p.exists() else None


def _md_table(df: pd.DataFrame) -> str:
    cols = list(df.columns)
    lines = ["| " + " | ".join(map(str, cols)) + " |", "|" + "---|" * len(cols)]
    for _, r in df.iterrows():
        lines.append("| " + " | ".join("" if pd.isna(v) else str(v).replace("|", "/").replace("\n", " ") for v in r) + " |")
    return "\n".join(lines)


def _pages(lst, n=8):
    if not lst:
        return "none"
    s = ", ".join(map(str, lst[:n]))
    return s + (f" (+{len(lst) - n} more)" if len(lst) > n else "")


def _elsewhere(hits: list[dict]) -> str:
    """Pages where the printed total recurs; quotes the line for the first page
    whose context mentions loans."""
    if not hits:
        return "not found"
    pages = ", ".join(f"p.{h['page']}" for h in hits)
    loan = next((h for h in hits if "loan" in h["context"].lower()), None)
    if loan:
        last = loan["context"].split(" / ")[-1]
        return f"{pages}; e.g. p.{loan['page']}: \"{last[:140]}\""
    return pages


def _manual() -> pd.DataFrame | None:
    p = INTERIM / "phase0_manual_checks.csv"
    return pd.read_csv(p) if p.exists() else None


def write_report() -> Path:
    banks = _load("phase0_banks.json") or {}
    annual = _load("phase0_annual.json") or []
    sust = _load("phase0_sustainability.json") or []
    inten = _load("phase0_intensity.json") or []
    ext = _load("extraction_test_results.json") or []
    manual = _manual()
    ann = pd.DataFrame(annual)
    out: list[str] = []
    w = out.append

    w("# Phase 0 results: feasibility checks\n")
    w(f"Generated by `src/bank_emissions/phase0_report.py` from the caches in `data/interim/`. "
      f"Bank-list check run at {banks.get('checked_utc', 'n/a')}. Page numbers are PDF page indices (1-based), "
      "which can differ from the page numbers printed in a report. File URLs, sizes and SHA-256 hashes are in "
      "`data/interim/phase0_sources.csv`. Results are reported without interpretation.\n")

    # ---- a. banks
    w("## a. Bank list\n")
    w(f"Source: NGX company directory API (`{banks.get('directory_file', '')}`, {banks.get('directory_records', '?')} issuer records, "
      f"SHA-256 `{banks.get('directory_sha256', '')[:16]}...`). Issuers in the NGX \"Banking\" sub-sector not on the candidate list: "
      f"{', '.join(banks.get('banking_subsector_not_in_registry', [])) or 'none'}.\n")
    rows = []
    latest = {r["symbol"]: r for r in annual if r.get("year") == max(YEARS)}
    for b in banks.get("banks", []):
        lr = latest.get(b["symbol"], {})
        rows.append({
            "NGX symbol": b["symbol"], "NGX name": b["ngx_company_name"],
            "Listed (directory)": "yes" if b["listed_on_ngx_directory"] else "no",
            "NGX sub-sector": b["ngx_subsector"], "Board": b["ngx_board"],
            "Listed-entity type": ENTITY_TYPE.get(b["symbol"], ""),
            "Countries named on subsidiary pages, FY2025 report (automated)": lr.get("foreign_countries_auto", "FY2025 report not available") or "none found",
        })
    w(_md_table(pd.DataFrame(rows)) + "\n")
    w("The country column is an automated text match on report pages that mention subsidiaries; it lists names found, "
      "not verified subsidiary locations. Manually verified entries are in the verification table at the end.\n")

    # ---- b. annual reports
    w("## b. Annual reports, 2020-2025\n")
    if not ann.empty:
        cov_rows = []
        for sym in BANKS:
            row = {"Bank": sym}
            n_ok = 0
            for y in YEARS:
                r = ann[(ann.symbol == sym) & (ann.year == y)]
                if r.empty or not r.iloc[0].get("source_used"):
                    row[str(y)] = "no file"
                    continue
                r = r.iloc[0]
                if r.get("sector_table_found") is True:
                    n_ok += 1
                    row[str(y)] = f"p.{int(r['sector_best_page'])} ({r['source_used']})"
                else:
                    row[str(y)] = f"not found ({r['source_used']})"
            row["Years with sector table located"] = f"{n_ok}/6"
            cov_rows.append(row)
        w("Coverage: PDF page of the located sector table and source used (`ir` = investor-relations site, `ngx` = NGX document library).\n")
        w(_md_table(pd.DataFrame(cov_rows)) + "\n")

        det = ann.copy()
        det["MB"] = (det.get("file_size_bytes") / 1e6).round(1)
        cols = {"symbol": "Bank", "year": "Year", "source_used": "Source", "MB": "MB", "n_pages": "Pages",
                "text_layer": "Text layer", "sector_best_page": "Sector page", "sector_candidate_pages": "Other candidate pages",
                "sector_gross_net_auto": "Gross/net (auto)", "sector_level_auto": "Group/bank (auto)"}
        for c in ("n_pages", "sector_best_page"):
            if c in det.columns:
                det[c] = det[c].map(lambda v: "" if pd.isna(v) else int(v))
        det = det[[c for c in cols if c in det.columns]].rename(columns=cols)
        w("A located page is the page the scan ranks highest within the sector note; the note often continues on the "
          "neighbouring candidate pages (group and bank tables, current and prior year).\n")
        if manual is not None:
            fm = manual[manual["check"] == "annual_report"].copy()
            if not fm.empty:
                w("### Table format by bank (read from the PDF page)\n")
                w("Basis (gross or net), level (group or bank), units and categories as printed, from one checked report per bank; "
                  "for other years only the table title on the located page was checked.\n")
                fm = fm.rename(columns={"symbol": "Bank", "document": "Report", "pdf_page": "PDF page", "finding_as_printed": "Format as printed"})
                fm["PDF page"] = fm["PDF page"].map(lambda v: "" if pd.isna(v) else int(v))
                fm["Report"] = fm["Report"].str.replace("data/raw/annual_reports/", "", regex=False)
                w(_md_table(fm[["Bank", "Report", "PDF page", "Format as printed"]]) + "\n")
        w("### Details per report\n")
        w("Gross/net and group/bank here are automated keyword readings of the located page (they flag words present on the page, "
          "for example 'gross' and 'impairment') and are superseded by the table above where they differ; "
          "sector categories as printed are in the `sector_categories_auto` column of `data/interim/phase0_sources.csv`.\n")
        w(_md_table(det) + "\n")
        w("Investor-relations access notes:\n")
        for sym, note in IR_NOTES.items():
            w(f"- {sym}: {note}")
        w("")

    # ---- c. sustainability
    w("## c. Sustainability disclosures\n")
    w("Automated page search. \"q\" pages carry the keyword together with an emissions unit (tCO2e etc.) or, for green "
      "or sustainable finance, a currency amount; \"m\" pages mention the keyword only. A \"q\" page indicates a likely "
      "quantitative disclosure, not a confirmed one.\n")

    def disc_cells(disc: dict) -> dict:
        cells = {}
        for k, lab in [("scope1", "Scope 1"), ("scope2", "Scope 2"), ("scope3", "Scope 3"),
                       ("financed_emissions", "Financed emissions"), ("pcaf", "PCAF"), ("green_loans", "Green/sustainable finance")]:
            d = disc.get(k, {"mention_pages": [], "quantified_pages": []})
            if not d["mention_pages"]:
                cells[lab] = "no"
            else:
                cells[lab] = f"q: {_pages(d['quantified_pages'], 5)}; m: {len(d['mention_pages'])} pp"
        return cells

    srows = []
    for r in sust:
        base = {"Bank": r["symbol"], "Document": f"sustainability report {r.get('year')}" if r.get("year") else "none located",
                "Status": r.get("download_attempts", "")}
        if r.get("disclosures"):
            base.update(disc_cells(json.loads(r["disclosures"])))
        srows.append(base)
    for r in annual:
        if r.get("year") == max(YEARS) and r.get("ar_disclosures"):
            kind = "annual report" if r.get("source_used") == "ir" else "NGX audited filing"
            base = {"Bank": r["symbol"], "Document": f"{kind} {r['year']}", "Status": "ok"}
            base.update(disc_cells(json.loads(r["ar_disclosures"])))
            srows.append(base)
    if srows:
        sdf = pd.DataFrame(srows).sort_values(["Bank", "Document"])
        w(_md_table(sdf.fillna("")) + "\n")

    # ---- d. intensity
    w("## d. Emission-intensity sources\n")
    irows = []
    for r in inten:
        cov = r.get("coverage")
        irows.append({"Source": r["source_key"], "URL": r["url"], "Status": r.get("download_attempts", ""),
                      "Pages": r.get("n_pages", ""), "SHA-256": (r.get("sha256") or "")[:16]})
    if irows:
        w(_md_table(pd.DataFrame(irows)) + "\n")
    for r in inten:
        if r.get("coverage"):
            w("Climate Watch API coverage for Nigeria (ISO NGA), by data source:\n")
            crow = []
            for k, v in json.loads(r["coverage"]).items():
                crow.append({"Data source": k, "Rows": v["rows"], "Years": f"{v['first_year']}-{v['last_year']}" if v["first_year"] else "none",
                             "Sectors": "; ".join(v["sectors"])})
            w(_md_table(pd.DataFrame(crow)) + "\n")
    notes = INTERIM / "phase0_intensity_notes.md"
    if notes.exists():
        w(notes.read_text(encoding="utf-8") + "\n")

    # ---- e. extraction
    w("## e. Extraction test\n")
    for r in ext:
        w(f"### {r['symbol']} {r['year']}, PDF page {r['page']}\n")
        w(f"Basis: {r['basis']}; units: {r['units']}. Output: `{r['csv']}` ({r['n_sector_rows']} sector rows). "
          f"camelot stream: {json.dumps({k: v for k, v in r['camelot_stream'].items() if k != 'largest_table_head'})}.\n")
        crow = []
        for c in r["checks"]:
            crow.append({"Column": c["column"], "Sum of sector rows": f"{c['sum_of_sectors']:,.0f}",
                         "Printed total": f"{c['table_total']:,.0f}" if c["table_total"] is not None else "n/a",
                         "Difference": f"{c['difference']:,.0f}" if c["difference"] is not None else "n/a",
                         "Same figure printed on other pages": _elsewhere(c["total_found_on_other_pages"])})
        w(_md_table(pd.DataFrame(crow)) + "\n")
        if r.get("notes"):
            w("Notes: " + "; ".join(r["notes"]) + "\n")
    extra = INTERIM / "extraction_test_notes.md"
    if extra.exists():
        w(extra.read_text(encoding="utf-8") + "\n")

    # ---- failures
    w("## Failures and gaps\n")
    fails = []
    for r in annual:
        if not r.get("source_used"):
            fails.append(f"- Annual report {r['symbol']} {r['year']}: {r.get('download_attempts')}")
        elif r.get("sector_table_found") is not True:
            fails.append(f"- Annual report {r['symbol']} {r['year']}: sector table not located by the automated scan ({r.get('text_layer', '')} text layer).")
        if r.get("scan_error"):
            fails.append(f"- Annual report {r['symbol']} {r['year']}: scan error {r['scan_error']}")
        if r.get("source_used") == "ngx" and r.get("ir_url"):
            fails.append(f"- Annual report {r['symbol']} {r['year']}: IR download failed ({r.get('download_attempts')}); NGX copy used.")
    for r in sust:
        if r.get("download_attempts") not in ("ok",):
            fails.append(f"- Sustainability report {r['symbol']}: {r.get('download_attempts')}")
    for r in inten:
        if not str(r.get("download_attempts", "")).startswith("ok"):
            fails.append(f"- Intensity source {r['source_key']}: {r.get('download_attempts')}")
    w("\n".join(fails) if fails else "None recorded.")
    w("")
    fnotes = INTERIM / "phase0_failure_notes.md"
    if fnotes.exists():
        w(fnotes.read_text(encoding="utf-8") + "\n")

    if manual is not None:
        w("## Manual verification: sustainability and foreign operations\n")
        w("Items checked by reading the page in the PDF (`data/interim/phase0_manual_checks.csv`); values are quoted as printed.\n")
        mv = manual[manual["check"] != "annual_report"].copy()
        mv["pdf_page"] = mv["pdf_page"].map(lambda v: "" if pd.isna(v) else int(v))
        mv["document"] = mv["document"].str.replace("data/raw/", "", regex=False)
        w(_md_table(mv.fillna("")) + "\n")

    DOCS.mkdir(exist_ok=True)
    path = DOCS / "phase0_results.md"
    path.write_text("\n".join(out), encoding="utf-8")
    return path


if __name__ == "__main__":
    print(write_report())
